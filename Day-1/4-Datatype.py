
# **datatypes** are classifications that specify what kind of data a variable can hold. Common examples include:
# - `int` (integers)
# - `str` (strings/text)
# - `float` (decimal numbers)
# - `bool` (boolean: True/False)
# - `list` (ordered collections)
# - `dict` (key-value pairs)
# - `tuple` (immutable sequences)

# Please share your code selection, and I'll generate the docstring for you!
# Example of different datatypes

# Integer
age = 25
print(f"age: {age}, type: {type(age)}")

# String
name = "Harish"
print(f"name: {name}, type: {type(name)}")

# Float
height = 5.9
print(f"height: {height}, type: {type(height)}")

# Boolean
is_student = True
print(f"is_student: {is_student}, type: {type(is_student)}")

# List
fruits = ["apple", "banana", "orange"]
print(f"fruits: {fruits}, type: {type(fruits)}")

# Dictionary
person = {"name": "Harish", "age": 25, "city": "Delhi"}
print(f"person: {person}, type: {type(person)}")

# Tuple
coordinates = (10, 20)
print(f"coordinates: {coordinates}, type: {type(coordinates)}")




